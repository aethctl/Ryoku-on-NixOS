func themeLookup(name string) ([][3]uint8, bool) {
	for _, p := range palettes {
		if p.name == name {
			return p.colors, true
		}
	}
	return nil, false
}

func themeNames() []string {
	names := make([]string, len(palettes))
	for i, p := range palettes {
		names[i] = p.name
	}
	return names
}
